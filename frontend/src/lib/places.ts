const split = (cities: string) => cities.split('|').filter(Boolean);

const byName = (a: string, b: string) => a.localeCompare(b, 'en');

/** Bangladesh first, then every other country in alphabetical order. */
export const COUNTRY_NAMES: string[] = [
  DEFAULT_COUNTRY,
  ...Object.keys(OTHER_COUNTRIES).sort(byName),
];

/** The cities offered for a country, alphabetical. Empty for a country that is not in the list. */
export function citiesOf(country: string): string[] {
  if (country === DEFAULT_COUNTRY) return split(BANGLADESH).sort(byName);
  const cities = OTHER_COUNTRIES[country];
  return cities ? split(cities).sort(byName) : [];
}
